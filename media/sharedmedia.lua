local sharedMediaRegister = LSM.Register

function LSM:Register(mediaType, key, data, ...)
	if type(data) == 'string' and data:sub(1, #legacyMediaRoot) == legacyMediaRoot then
		data = mediaRoot .. data:sub(#legacyMediaRoot + 1)
	end

	return sharedMediaRegister(self, mediaType, key, data, ...)
end

